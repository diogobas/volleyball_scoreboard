import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const source = JSON.parse(await readFile(new URL('supabase/maintenance/tuesday-2026-11-03-source.json', root), 'utf8'));
const completion = (await readFile(new URL('supabase/maintenance/complete-tuesday-2026-11-03-points.sql.in', root), 'utf8'))
  .replace('__SCREENSHOT_SOURCE__', JSON.stringify(source).replaceAll("'", "''"));
const references = await readFile(new URL('supabase/migrations/20261108001000_repair_readable_references.sql', root), 'utf8');
const attendance = await readFile(new URL('supabase/migrations/20261108001200_player_attendance_statistics.sql', root), 'utf8');
const teams = await readFile(new URL('supabase/migrations/20261108001100_historical_team_changes.sql', root), 'utf8');
// One transaction: a missing registration or conflicting edit rolls back the entire repair.
const stripTransactions = sql => sql.replace(/^begin;\s*$/gm, '').replace(/^commit;\s*$/gm, '');
const verification = completion.slice(completion.indexOf('\nselect p.name'));
const mutation = completion.slice(0, completion.indexOf('\nselect p.name'));
await writeFile(new URL('supabase/maintenance/repair-tuesday-2026-11-03.sql', root),
  '-- Generated by node scripts/prepare-november-repair.mjs. Run this WHOLE file in the Supabase SQL Editor.\n' +
  '-- Repairs short references and completes the existing November 3 match; no new match or player is created.\nbegin;\n' +
  [references, teams, attendance, mutation].map(stripTransactions).join('\n') + '\ncommit;\n' + verification);
console.log('Prepared supabase/maintenance/repair-tuesday-2026-11-03.sql');
